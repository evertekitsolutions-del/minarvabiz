import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import ts from "typescript";
import { createRequire } from "node:module";
const source = readFileSync(new URL("../src/warehouse-transfer-receipt.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
new Function("module", "exports", "require", js)(module, module.exports, createRequire(import.meta.url));
const { validateWarehouseTransferReceipt: check } = module.exports;
const scope = { tenantId: "t", companyId: "c", destinationBranchId: "b", destinationWarehouseId: "w" };
const line = { lineId: "l1", skuId: "sku", dispatchedMinorUnits: 100, previouslyReceivedMinorUnits: 40 };
const authority = { scope, transferId: "transfer", transferRevision: 2, status: "partially_received", lines: [line] };
const request = { scope, transferId: "transfer", transferRevision: 2, idempotencyKey: "receipt-1", lines: [{ ...line, receiveMinorUnits: 60 }] };
test("accepts exact remaining quantity", () => assert.deepEqual({ ...check(request, authority) }, { ok: true, remainingMinorUnitsByLine: { l1: 0 } }));
test("rejects cross-tenant scope", () => assert.equal(check({ ...request, scope: { ...scope, tenantId: "other" } }, authority).ok, false));
test("rejects over receipt", () => assert.equal(check({ ...request, lines: [{ ...line, receiveMinorUnits: 61 }] }, authority).ok, false));
test("rejects stale revision", () => assert.equal(check({ ...request, transferRevision: 1 }, authority).ok, false));
test("rejects duplicate lines", () => assert.equal(check({ ...request, lines: [request.lines[0], request.lines[0]] }, { ...authority, lines: [line, { ...line, lineId: "l2" }] }).ok, false));
test("rejects zero receipt", () => assert.equal(check({ ...request, lines: [{ ...line, receiveMinorUnits: 0 }] }, authority).ok, false));
test("rejects closed transfer", () => assert.equal(check(request, { ...authority, status: "received" }).ok, false));
